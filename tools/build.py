#!/usr/bin/env python3
"""Build the live site files from their sources, for a faster first load.

Edit these sources, then run:  python3 tools/build.py
  index.src.html -> index.html   (runs of data/*.js script tags become a few bundles)
  sw.src.js      -> sw.js        (the offline file list uses the bundles)
  data/examples.js -> data/ex/*.js + data/ex/map.js  (picture examples split into small chunks)

The individual data files stay in the repository as the sources; the browser loads the bundles.
"""
import json, os, re, sys, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
LIMIT = 1_200_000          # target bundle size in bytes
EX_LIMIT = 160_000         # target picture-chunk size in bytes

def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()

def write(p, s):
    os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(s)

# ---------- 3. Split the picture examples ----------
ex = read("data/examples.js")
start = ex.index('{"', ex.index("window.EXAMPLES"))
data = json.loads(ex[start:ex.rindex("}") + 1])
os.makedirs("data/ex", exist_ok=True)
for f in os.listdir("data/ex"):
    os.remove(os.path.join("data/ex", f))
# Chunk boundaries depend on the article ids themselves (content-defined), so adding or editing
# one article changes only its own chunk and returning visitors re-download very little.
def cut(name, size, lo, hi, mod):
    return size >= hi or (size >= lo and int(hashlib.sha1(name.encode()).hexdigest()[:6], 16) % mod == 0)
chunks, cur, size = [], {}, 0
for k in data:
    s = len(json.dumps(data[k], ensure_ascii=False).encode())
    if cur and size + s > EX_LIMIT * 1.6:
        chunks.append(cur); cur, size = {}, 0
    cur[k] = data[k]; size += s
    if cut(k, size, EX_LIMIT // 2, EX_LIMIT * 1.6, 12):
        chunks.append(cur); cur, size = {}, 0
if cur:
    chunks.append(cur)
emap, names = {}, []
for i, c in enumerate(chunks):
    body = json.dumps(c, ensure_ascii=False, separators=(",", ":"))
    h = hashlib.sha1(body.encode()).hexdigest()[:8]
    name = f"ex-{h}"
    write(f"data/ex/{name}.js", "// Generated by tools/build.py from data/examples.js. Do not edit.\nObject.assign(window.EXAMPLES=window.EXAMPLES||{}," + body + ");\n")
    for k in c:
        emap[k] = i
    names.append(name)
write("data/ex/map.js", "// Generated by tools/build.py: which picture chunk holds each article's examples.\nwindow.EXCH={files:" + json.dumps(names) + ",of:" + json.dumps(emap, separators=(",", ":")) + "};\n")

# ---------- 1. Bundle the data scripts ----------
src = read("index.src.html")
TAG = re.compile(r'<script src="(data/[^"]+\.js)"></script>')
os.makedirs("data/b", exist_ok=True)
for f in os.listdir("data/b"):
    os.remove(os.path.join("data/b", f))

bundles, out, pos, n = [], [], 0, 0
# find runs of consecutive data script tags (only whitespace between them)
run_rx = re.compile(r'(?:<script src="data/[^"]+\.js"></script>\s*)+')
for m in run_rx.finditer(src):
    out.append(src[pos:m.start()])
    files = TAG.findall(m.group(0))
    # Content-defined bundles: a bundle ends after a file whose name hash matches, so inserting or
    # editing one data file changes only the bundle that holds it, not every bundle after it.
    groups, cur, size = [], [], 0
    for f in files:
        s = os.path.getsize(f)
        if cur and size + s > LIMIT * 1.5:
            groups.append(cur); cur, size = [], 0
        cur.append(f); size += s
        if cut(f, size, LIMIT // 4, LIMIT * 1.5, 7):
            groups.append(cur); cur, size = [], 0
    if cur:
        groups.append(cur)
    tags = []
    for g in groups:
        n += 1
        body = "".join(f"/* {f} */\n{read(f)}\n;\n" for f in g)
        h = hashlib.sha1(body.encode()).hexdigest()[:8]
        name = f"data/b/b-{h}.js"
        write(name, "// Generated by tools/build.py from the files named in the comments. Do not edit.\n" + body)
        bundles.append(name)
        tags.append(f'<script src="{name}"></script><script>window.EPL&&EPL()</script>')
    trail = re.search(r'\s*$', m.group(0)).group(0)
    out.append("".join(tags) + trail)
    pos = m.end()
out.append(src[pos:])
html = "".join(out).replace("__NB__", str(len(bundles)))
html = re.sub(r'^(<!DOCTYPE html>)', r'\1<!-- Generated by tools/build.py from index.src.html. Edit that file instead. -->', html, count=1, flags=re.I)
write("index.html", html)

# ---------- 2. Offline file list ----------
sw = read("sw.src.js")
m = re.search(r'CORE=\[(.*?)\];', sw, re.S)
if not m:
    sys.exit("CORE list not found in sw.src.js")
items = json.loads("[" + m.group(1) + "]")
bundled = set(TAG.findall(src))
core, done = [], False
for it in items:
    p = it[2:] if it.startswith("./") else it
    if p == "data/examples.js":
        core += [f"./data/ex/{x}.js" for x in names]
        continue
    if p in bundled:
        if not done:
            core += ["./" + b for b in bundles]; done = True
        continue
    core.append(it)
if not done:
    core += ["./" + b for b in bundles]
sw = sw[:m.start()] + "CORE=[" + ", ".join(json.dumps(c) for c in core) + "];" + sw[m.end():]
write("sw.js", "// Generated by tools/build.py from sw.src.js. Edit that file instead.\n" + sw)

print(f"{len(bundled)} data files -> {len(bundles)} bundles; {len(data)} picture sets -> {len(chunks)} chunks")
